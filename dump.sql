-- Започваме транзакция
BEGIN;

-- Таблица с всички книги
CREATE TABLE public.books (
    -- Уникален номер на всяка книга
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Заглавие на книгата
    title text NOT NULL,

    -- Автор на книгата
    author text NOT NULL,

    -- Година на издаване, трябва да е положително число
    published_year integer NOT NULL CHECK (published_year > 0)
);

-- Таблица с учениците
CREATE TABLE public.students (
    -- Уникален номер на ученика
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Име на ученика
    name text NOT NULL
);

-- Таблица, която пази кой е взел книга
CREATE TABLE public.loans (
    -- Уникален номер на заемането
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- ID на книгата, свързано с таблицата books
    book_id integer NOT NULL REFERENCES public.books(id),

    -- ID на ученика, свързано с таблицата students
    student_id integer NOT NULL REFERENCES public.students(id),

    -- Дата, на която книгата е взета
    borrowed_on date NOT NULL,

    -- Дата на връщане. NULL означава, че не е върната
    returned_on date,

    -- Не позволяваме книгата да бъде върната преди да е взета
    CONSTRAINT return_not_before_borrow
        CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);

-- Не позволяваме една книга да бъде взета
-- едновременно от двама ученици
CREATE UNIQUE INDEX only_one_active_loan_per_book
    ON public.loans (book_id)
    WHERE returned_on IS NULL;

